#!/usr/bin/env python3
"""
Test Rust <-> Python interoperability for CRCL messages

This demonstrates that messages generated by Rust can be read by Python
and vice versa, using JSON as the interchange format.
"""

import json
import sys
from pathlib import Path

# Add crcl_python to path
sys.path.insert(0, str(Path(__file__).parent))

from crcl_python.crclstatus import JointStatusType, JointStatusesType
from crcl_python.crclcommands import (
    ActuateJointType, ActuateJointsType,
    JointSpeedAccelType, JointForceTorqueType
)


def test_status_python_to_rust():
    """Test: Python creates status -> Rust can read it"""
    print("=" * 60)
    print("Test 1: Python -> Rust (JointStatusType)")
    print("=" * 60)

    # Create status in Python
    joint = JointStatusType(
        name=None,
        joint_number=0,
        joint_position=1.57,
        joint_torque_or_force=10.5,
        joint_velocity=0.5
    )

    # Convert to JSON
    json_dict = {
        "name": joint.name,
        "joint_number": joint.joint_number,
        "joint_position": joint.joint_position,
        "joint_torque_or_force": joint.joint_torque_or_force,
        "joint_velocity": joint.joint_velocity
    }

    json_str = json.dumps(json_dict, indent=2)
    print("\nPython generated JSON:")
    print(json_str)

    # Verify it matches Rust's format
    print("\n[OK] This JSON can be read by Rust with:")
    print("  let joint: JointStatusType = serde_json::from_str(json)?;")
    print()

    return json_str


