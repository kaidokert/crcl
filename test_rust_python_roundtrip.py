def test_rust_to_python():
    """Test: Simulated Rust JSON -> Python can read it"""
    print("=" * 60)
    print("Test 5: Rust -> Python (reading Rust-generated JSON)")
    print("=" * 60)

    # Simulate JSON that Rust would generate
    rust_json = """{
  "name": null,
  "command_id": 42,
  "guard": [],
  "actuate_joint": [
    {
      "name": null,
      "joint_number": 0,
      "joint_position": 1.57,
      "joint_details": {
        "name": null,
        "joint_speed": 1.5,
        "joint_accel": 0.5
      }
    }
  ],
  "joint_tolerances": null
}"""

    print("\nRust-generated JSON:")
    print(rust_json)

    # Parse in Python
    data = json.loads(rust_json)

    # Reconstruct ActuateJointsType
    actuate_joints = []
    for aj_data in data["actuate_joint"]:
        jd_data = aj_data["joint_details"]

        # Determine type based on fields present
        if "joint_speed" in jd_data or "joint_accel" in jd_data:
            joint_details = JointSpeedAccelType(
                name=jd_data.get("name"),
                joint_speed=jd_data.get("joint_speed"),
                joint_accel=jd_data.get("joint_accel")
            )
        else:
            joint_details = JointForceTorqueType(
                name=jd_data.get("name"),
                setting=jd_data.get("setting"),
                change_rate=jd_data.get("change_rate")
            )

        actuate_joint = ActuateJointType(
            name=aj_data.get("name"),
            joint_number=aj_data["joint_number"],
            joint_position=aj_data["joint_position"],
            joint_details=joint_details
        )
        actuate_joints.append(actuate_joint)

    command = ActuateJointsType(
        name=data.get("name"),
        command_id=data["command_id"],
        guard=data.get("guard", []),
        actuate_joint=actuate_joints,
        joint_tolerances=data.get("joint_tolerances")
    )

    print("\n[OK] Successfully parsed in Python!")
    print(f"  Command ID: {command.command_id}")
    print(f"  Joints: {len(command.actuate_joint)}")
    print(f"  Joint 0 type: {type(command.actuate_joint[0].joint_details).__name__}")
    print(f"  Joint 0 speed: {command.actuate_joint[0].joint_details.joint_speed}")
    print()


